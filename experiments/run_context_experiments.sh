run_configuration() {
    local run_id="$1"
    shift
    echo "Starting $run_id"
    env \
        "${COMMON_ENV[@]}" \
        "RUN_ID=$run_id" \
        "OUTPUT_ROOT=$REPOSITORY_ROOT/outputs/$run_id" \
        "$@" \
        bash ./run_pipeline.sh
}

